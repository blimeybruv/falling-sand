/**
 * How the generic engine moves a material.
 * - empty:  air. Never updated.
 * - static: never moves (stone, wood, plant).
 * - powder: falls, slides off diagonally, sinks through lighter liquids.
 * - liquid: falls, then spreads sideways; denser liquids sink through lighter ones.
 * - gas:    rises and drifts; usually has a lifetime.
 */
export type Kind = 'empty' | 'static' | 'powder' | 'liquid' | 'gas';

/** Palette tab a material appears under. */
export type Category = 'ground' | 'fluid' | 'fire' | 'life';
export const CATEGORIES: readonly (readonly [Category, string])[] = [
  ['ground', 'Ground'],
  ['fluid', 'Liquids & gases'],
  ['fire', 'Fire & blasts'],
  ['life', 'Life'],
];

/**
 * A simple two-material reaction: while a cell of this material touches `with` (4-neighbourhood),
 * each frame there is a `chance` that this cell becomes `into` and/or the other becomes `otherInto`.
 * Recipes for Discovery mode are mostly reactions like these.
 */
export interface Reaction {
  with: MaterialId;
  chance: number;
  into?: MaterialId;
  otherInto?: MaterialId;
  /** Only while this cell is burning. */
  whileBurning?: boolean;
  /** Only when the other cell is on this side of this one (e.g. 'above': it's on top). */
  side?: 'above' | 'below' | 'beside';
  /** Only when this cell is at least this hot. */
  minTemp?: number;
}

/** Per-material hook. Return true if the cell was fully handled (moved, transformed or removed). */
export type UpdateFn = (world: World, x: number, y: number, i: number) => boolean;

export interface MaterialDef {
  id: MaterialId;
  name: string;
  /** Keyboard shortcut shown in the palette ('' for none). */
  key: string;
  kind: Kind;
  /** Palette tab. */
  category: Category;
  /**
   * Relative density. A moving particle may swap with a liquid, gas or empty cell that is
   * lighter (moving down) or heavier (moving up). Air (Empty) is 1.
   */
  density: number;
  /** Base colour, 0-255 per channel. */
  colour: readonly [number, number, number];
  /** Optional second colour: particle shades blend between `colour` and this (e.g. fire). */
  colourEnd?: readonly [number, number, number];
  /** Brightness variation per particle, 0..1, so piles look textured. */
  colourJitter: number;
  /** Chance per frame, per burning neighbour, of catching fire. 0 = never burns. */
  flammability: number;
  /** Frames a burning cell keeps burning [min, max]. */
  burnTime: readonly [number, number];
  /** Chance per frame that touching water puts this material out while it burns. */
  extinguishChance: number;
  /** What a burning cell becomes once its burn time runs out. */
  burnsInto: MaterialId;
  /** Sometimes leaves this instead of `burnsInto` when it burns out (e.g. ash). */
  residue?: { into: MaterialId; chance: number };
  /** How hot it burns (default BURNING_TEMP). */
  burnTemp?: number;
  /** Chance per frame a burning cell throws off a flame above it (default 0.25). */
  flames: number;
  /** What a burning cell now and then gives off above it besides flames (default Smoke). */
  fumes?: MaterialId;
  /** Lifetime in frames [min, max] for short-lived materials (gas, fire). Omit for permanent ones. */
  lifetime?: readonly [number, number];
  /** What a short-lived cell becomes when its lifetime ends (Empty unless set), and how often. */
  decay?: { into: MaterialId; chance: number };
  /** Liquids: how many cells sideways it can flow per frame. */
  dispersion: number;
  /** Liquids and powders: chance per frame of skipping sideways/diagonal movement (stickiness). */
  viscosity: number;
  /** Gases: chance per frame of trying to rise straight up (otherwise it drifts). */
  rise: number;
  /** Cannot be destroyed by explosions, fire or acid. (The eraser still clears it.) */
  indestructible: boolean;
  /** Acid can't dissolve it (but explosions can still destroy it). */
  acidProof: boolean;
  /** What an explosion's blast turns it into, instead of clearing it (iron shatters into filings). */
  shattersInto?: MaterialId;
  /** Puts out fire and burning cells it touches, like water (water, salt water, foam). */
  extinguishes: boolean;
  /** Carries electricity (see World.updateElectricity). */
  conducts: boolean;
  /**
   * Explodes when it finishes burning (or, with no burnTime, after a short fuse once lit).
   * `impactSpeed`: frames of falling before a hard landing sets it off (omit: not impact-sensitive).
   * `chance`: probability of exploding when it burns out (omit: always); otherwise it becomes `burnsInto`.
   */
  explosive?: { radius: number; impactSpeed?: number; chance?: number };

  // ---- temperature (see World.updateTemperature). Ambient is AMBIENT_TEMP (20).
  /** 0..0.25: how quickly a cell takes on its neighbours' average temperature. */
  conductivity: number;
  /** 0..1: how quickly it drifts back to ambient temperature when nothing heats it. */
  cooling: number;
  /** Heat source or sink: holds itself towards `temp` at `rate` (0..1) per frame. Replaces `cooling`. */
  heat?: { temp: number; rate: number };
  /**
   * Turns into `into` (keeping its temperature) once hotter than `temp`; with `sometimes`, now and
   * then into something else instead (boiling water leaving a grain of salt).
   */
  above?: { temp: number; into: MaterialId; sometimes?: { into: MaterialId; chance: number } };
  /** Turns into `into` (keeping its temperature) once colder than `temp`: setting solid again. */
  below?: { temp: number; into: MaterialId };
  /** Temperature a fresh particle starts at, if not room temperature (molten things start hot). */
  startTemp?: number;
  /** Flammable materials catch fire once this hot, as well as from touching fire. */
  ignitesAt?: number;

  // ---- sunlight (when the Sun setting is on, light comes straight down each column)
  /** Whether sunlight shines through it. Defaults to true for gases and air, false otherwise. */
  transparent?: boolean;
  /**
   * In direct sunlight, now and then (`chance` per sunlit visit, at full sun) turns into `into`:
   * water evaporating, mud drying, a cloud burning off from the top. With `sometimes`, now and
   * then into something else instead (salt water leaving salt).
   */
  sunlit?: { chance: number; into: MaterialId; sometimes?: { into: MaterialId; chance: number } };
  /**
   * Under a clear night sky (the first thing the sky reaches in its column), now and then
   * (`chance` per visit, on the clearest night) turns into `into`: mist rising off water.
   */
  night?: {
    chance: number;
    into: MaterialId;
    sometimes?: { into: MaterialId; chance: number };
    /** Once the night sky has chilled it below `temp`, it turns into `into` instead (a pond skinning over). */
    cold?: { temp: number; into: MaterialId };
  };

  // ---- other
  /** 0..1: how strongly wind pushes it sideways. */
  wind: number;
  /**
   * Powders: 0..1, the chance per frame (in a full wind) that a grain lying exposed is lifted a cell
   * downwind, so dunes creep and snow piles into drifts.
   */
  drifts?: number;
  /** Renderer: the colour shimmers over time (lava). */
  glow?: boolean;
  /** Renderer: fade out over this many final frames of its lifetime (gases default to 40). */
  fadeFrames?: number;
  /** Renderer: brightness flickers frame to frame. */
  flicker?: boolean;
  /**
   * Vents: a reservoir under pressure finding a way out. Now and then (on average every `every`
   * frames) it releases a burst of `what` (sometimes something else) into open air, up through any
   * pool of fluid above it, optionally launched upward at `launch` cells a frame. It holds
   * `reservoir` cells in all, then dies into `spent`, so no vent can flood the grid.
   */
  emits?: {
    what: MaterialId;
    sometimes?: { what: MaterialId; chance: number };
    every: number;
    burst: readonly [number, number];
    reservoir: number;
    spent: MaterialId;
    launch?: number;
  };
  /** Renderer: shaded by depth, as part of a cloud's body (bright tops, darker bases). */
  cloudShading?: boolean;
  /** Renderer: the colour it glows while its `life` counter is above zero (a lit lamp). */
  litColour?: readonly [number, number, number];
  /** Renderer: the colour it glows while carrying a pulse (instead of the usual spark), e.g. neon. */
  chargeColour?: readonly [number, number, number];
  /** Two-material reactions; see Reaction. */
  reactions?: readonly Reaction[];
  /** Optional extra behaviour; runs before the generic movement for its kind. */
  update?: UpdateFn;
  /** One line for the palette tooltip and the README. */
  description: string;
}

